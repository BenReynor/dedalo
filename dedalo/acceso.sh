#!/usr/bin/env bash
# acceso.sh — installs/updates the DYNAMIC Dédalo shortcut.
#
# Creates or regenerates:
#   ~/.local/bin/dedalo                  dynamic launcher (locates the project)
#   ~/.local/share/icons/dedalo.svg      icon with a stable path
#   ~/Escritorio/dedalo.desktop      shortcut whose Exec points to the launcher
#
# This way the shortcut does NOT break when moving/renaming the project: the
# launcher looks for its marker (the dedalo/ folder) inside ~/Escritorio,
# ~/Documentos and ~. Re-runnable whenever you want.
set -euo pipefail

# Real location of this script, wherever it is, even if it is a symlink.
# `readlink -f` is GNU: it does not exist on macOS (BSD), so we resolve
# symlinks by hand and end up with an absolute path.
ORIGEN="${BASH_SOURCE[0]:-$0}"
while [ -L "$ORIGEN" ]; do
    _dest="$(readlink "$ORIGEN")"
    case "$_dest" in
        /*) ORIGEN="$_dest" ;;
        *) ORIGEN="$(cd "$(dirname "$ORIGEN")" && pwd)/$_dest" ;;
    esac
done
ORIGEN="$(cd "$(dirname "$ORIGEN")" && pwd)/$(basename "$ORIGEN")"
PAQUETE="$(dirname "$ORIGEN")"
PROYECTO="$(dirname "$PAQUETE")"

BIN="$HOME/.local/bin"
# Named icon in the user's hicolor theme (`Icon=dedalo`): desktops cache icons
# by file path, so pointing at a fixed .svg never showed a changed icon.
DIR_ICONOS="$HOME/.local/share/icons/hicolor/scalable/apps"
LANZADOR="dedalo"

# Real desktop folder of the user: we prefer xdg-user-dir (respects locales
# like ~/Bureau or ~/Schreibtisch) and fall back to the usual paths.
DIR_DESKTOP=""
if command -v xdg-user-dir >/dev/null 2>&1; then
    DIR_DESKTOP="$(xdg-user-dir DESKTOP 2>/dev/null || true)"
fi
[ -d "$DIR_DESKTOP" ] || DIR_DESKTOP="$HOME/Escritorio"
[ -d "$DIR_DESKTOP" ] || DIR_DESKTOP="$HOME/Desktop"
if [ ! -d "$DIR_DESKTOP" ]; then
    echo "No encuentro tu carpeta de escritorio (~/Escritorio ni ~/Desktop)." >&2
    echo "Re-genera el acceso con:  bash <ruta-del-proyecto>/dedalo/acceso.sh" >&2
    exit 1
fi
DESKTOP_FILE="$DIR_DESKTOP/dedalo.desktop"

mkdir -p "$BIN" "$DIR_ICONOS"
cp "$PAQUETE/icono.svg" "$DIR_ICONOS/dedalo.svg"
gtk-update-icon-cache -q -f -t "$HOME/.local/share/icons/hicolor" 2>/dev/null || true

# ── 1) Dynamic resolver: finds the project via its marker ────────────────────
# The checkout that installs the shortcut is recorded first, so the launcher is
# deterministic when several copies exist. The disk search stays as a fallback
# for a moved/renamed folder (that is what makes the shortcut portable).
{
printf '#!/usr/bin/env bash\n'
printf '# Dédalo — dynamic launcher (generated by dedalo/acceso.sh).\n'
printf '# Runs the checkout that installed it; if that one is gone it searches\n'
printf '# the disk for another one and runs its lanzar.sh.\n'
printf 'set -euo pipefail\n\n'
printf 'PROYECTO_FIJO=%q\n\n' "$PROYECTO"
cat <<'RESOLVER'
BASES=("$HOME/Escritorio" "$HOME/Desktop" "$HOME/Documentos" "$HOME")

# Version of a checkout: `version = "x.y.z"` in its pyproject.toml (0 if absent).
version_de() {
    local f="$1/pyproject.toml" v
    [ -f "$f" ] || { printf '0\n'; return; }
    v="$(sed -n 's/^version *= *"\([^"]*\)".*/\1/p' "$f" | head -n 1)"
    printf '%s\n' "${v:-0}"
}

# Prints 1 when the first version is greater than the second.
version_mayor() {
    awk -v a="$1" -v b="$2" 'BEGIN {
        n = split(a, A, "."); m = split(b, B, ".")
        k = (n > m ? n : m)
        for (i = 1; i <= k; i++) {
            x = A[i] + 0; y = B[i] + 0
            if (x > y) { print 1; exit }
            if (x < y) { print 0; exit }
        }
        print 0
    }'
}

# With several checkouts on disk (e.g. an old copy kept around) prefer the
# newest version instead of whichever `find` happens to list first.
buscar_proyecto() {
    local base dir proy v mejor="" mejor_v=""
    if [ -n "$PROYECTO_FIJO" ] && [ -f "$PROYECTO_FIJO/dedalo/__init__.py" ] \
            && [ -f "$PROYECTO_FIJO/lanzar.sh" ]; then
        printf '%s\n' "$PROYECTO_FIJO"
        return 0
    fi
    for base in "${BASES[@]}"; do
        [ -d "$base" ] || continue
        while IFS= read -r dir; do
            case "$dir" in
                *"/.git/"*|*"/venv/"*|*"/.venv/"*|*"/env/"*|*"/.env/"*|*"/site-packages/"*|*"/node_modules/"*|*"/__pycache__/"*) continue ;;
            esac
            [ -f "$dir/__init__.py" ] || continue
            [ -f "$dir/icono.svg" ] || continue
            proy="$(dirname "$dir")"
            v="$(version_de "$proy")"
            if [ -z "$mejor" ] || [ "$(version_mayor "$v" "$mejor_v")" = "1" ] \
                    || { [ "$v" = "$mejor_v" ] && [ "$proy" -nt "$mejor" ]; }; then
                mejor="$proy"
                mejor_v="$v"
            fi
        done < <(
            find "$base" -maxdepth 6 -type d -name dedalo -print 2>/dev/null
        )
    done
    [ -n "$mejor" ] || return 1
    printf '%s\n' "$mejor"
}

if ! PROYECTO="$(buscar_proyecto)"; then
    echo "Dédalo: no encuentro el proyecto (dedalo/ bajo ~/Escritorio, ~/Documentos o ~)." >&2
    echo "Re-genera el acceso con:  bash <ruta-del-proyecto>/dedalo/acceso.sh" >&2
    exit 1
fi

exec "$PROYECTO/lanzar.sh"
RESOLVER
} > "$BIN/$LANZADOR"
chmod +x "$BIN/$LANZADOR"

# ── 2) Desktop shortcut ──────────────────────────────────────────────────────
cat > "$DESKTOP_FILE" <<EOF
[Desktop Entry]
Version=1.0
Type=Application
Name=Dédalo
Comment=Panel de control de Dédalo
Exec=$BIN/$LANZADOR
Icon=dedalo
Terminal=false
StartupWMClass=dedalo
Categories=Development;Utility;
Keywords=dedalo;ia;
EOF
chmod +x "$DESKTOP_FILE"

# Mark as trusted on GNOME (best effort; does not fail if unavailable).
if command -v gio >/dev/null 2>&1; then
    gio set "$DESKTOP_FILE" metadata::trusted true 2>/dev/null || true
fi

echo "Acceso dinámico instalado:"
echo "  · $DESKTOP_FILE"
echo "  · $BIN/$LANZADOR"
echo "  · $DIR_ICONOS/dedalo.svg"
echo "El acceso localiza el proyecto solo; puedes moverlo libremente."