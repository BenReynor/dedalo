"""Project map (mapeo.txt): modules, tests, HTTP routes and CLI commands.

Pure Python so it works on every OS and for every stack the gate templates
know about; the old `mapear.sh` only understood Django, Node and Rust and
needed `_env.sh`, which template installs do not ship. A project that
customized its own `mapear.sh` keeps using it (see `generar`).
"""

import filecmp
import os
import re
import subprocess
import time

from . import plantillas, rutas

# Directories never worth mapping (dependencies, builds, caches, tooling).
IGNORADOS = frozenset({
    ".git", ".dedalo", ".venv", "venv", "env", "node_modules", "__pycache__",
    "target", "dist", "build", ".pytest_cache", ".ruff_cache", ".mypy_cache",
    ".tox", ".idea", ".vscode", "vendor", ".gradle", "bin", "obj", ".dart_tool",
})

EXT_CODIGO = {
    ".py": "python", ".js": "node", ".mjs": "node", ".cjs": "node",
    ".ts": "node", ".tsx": "node", ".jsx": "node", ".vue": "node",
    ".rs": "rust", ".go": "go", ".java": "java", ".kt": "kotlin",
    ".cs": "csharp", ".c": "cpp", ".cc": "cpp", ".cpp": "cpp", ".h": "cpp",
    ".hpp": "cpp", ".sh": "shell", ".rb": "ruby", ".php": "php",
    ".swift": "swift", ".dart": "dart", ".html": "web", ".css": "web",
}

# Per-section caps: the map must stay cheap to read for the agent.
MAX_MODULOS = 300
MAX_TESTS = 120
MAX_RUTAS = 120
TAM_MAX_FICHERO = 512 * 1024

_ES_TEST = re.compile(
    r"(^|/)(tests?|__tests__|spec)/|(^|/)test_[^/]*$|_test\.[a-z]+$"
    r"|\.(test|spec)\.[a-z]+$|Tests?\.(java|kt|cs)$")

_TESTS = {
    "python": re.compile(r"^\s*(?:async\s+)?def\s+(test_\w+)", re.M),
    "node": re.compile(r"""\b(?:it|test)\s*\(\s*['"`]([^'"`]+)""", re.M),
    "go": re.compile(r"^func\s+(Test\w+)\s*\(", re.M),
    "rust": re.compile(r"#\[(?:tokio::)?test\]\s*(?:async\s+)?fn\s+(\w+)", re.M),
}

_METODO = r"(get|post|put|patch|delete|route|api_route|websocket)"
_RUTAS = (
    # Django: path("x/", view) / re_path(...)
    ("django", re.compile(r"""\b(?:re_)?path\(\s*r?['"]([^'"]*)['"]""")),
    # Flask / FastAPI / Starlette decorators
    ("python", re.compile(
        r"""@\w+\.""" + _METODO + r"""\(\s*['"]([^'"]+)['"]""", re.I)),
    # Express / Koa / Fastify style routers
    ("node", re.compile(
        r"""\b(?:app|router|server|fastify)\.(get|post|put|patch|delete|all|use)"""
        r"""\(\s*['"`](/[^'"`]*)['"`]""")),
    # Rust: actix attributes and axum .route()
    ("rust", re.compile(r"""#\[(get|post|put|patch|delete)\(\s*"([^"]+)\"""")),
    ("rust", re.compile(r"""\.route\(\s*"([^"]+)\"""")),
    # Go: net/http and gin/echo/chi
    ("go", re.compile(
        r"""\b(?:HandleFunc|Handle|GET|POST|PUT|PATCH|DELETE|Get|Post|Put|Delete)"""
        r"""\(\s*"(/[^"]*)\"""")),
)

_CLI = (
    ("argparse", re.compile(r"""\.add_parser\(\s*['"]([\w:-]+)['"]""")),
    ("click/typer", re.compile(r"""@\w+\.command\(\s*(?:name\s*=\s*)?['"]([\w:-]+)['"]""")),
    ("click/typer", re.compile(r"""@\w+\.command\(\s*\)\s*\n\s*def\s+(\w+)""")),
)


def _listar(proyecto):
    """Project files relative to its root, honoring .gitignore when possible."""
    try:
        r = subprocess.run(
            ["git", "ls-files", "--cached", "--others", "--exclude-standard"],
            cwd=proyecto, capture_output=True, text=True, timeout=20)
        if r.returncode == 0:
            ficheros = [f for f in r.stdout.splitlines() if f]
            return sorted(f for f in ficheros
                          if not set(f.split("/")[:-1]) & IGNORADOS)
    except (OSError, subprocess.TimeoutExpired):
        pass
    ficheros = []
    for raiz, dirs, nombres in os.walk(proyecto):
        dirs[:] = sorted(d for d in dirs if d not in IGNORADOS)
        rel = os.path.relpath(raiz, proyecto)
        for n in sorted(nombres):
            ficheros.append(n if rel == "." else f"{rel}/{n}".replace(os.sep, "/"))
    return ficheros


def _leer(proyecto, rel):
    ruta = os.path.join(proyecto, rel)
    try:
        if os.path.getsize(ruta) > TAM_MAX_FICHERO:
            return ""
        with open(ruta, encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def _recortar(lineas, maximo, que):
    if len(lineas) <= maximo:
        return lineas
    return lineas[:maximo] + [f"  … ({len(lineas) - maximo} {que} más)"]


def construir(proyecto):
    """Returns the mapeo.txt text for `proyecto`."""
    ficheros = _listar(proyecto)
    codigo = [f for f in ficheros
              if os.path.splitext(f)[1].lower() in EXT_CODIGO]
    tests = [f for f in codigo if _ES_TEST.search(f)]
    modulos = [f for f in codigo if f not in set(tests)]
    stacks = plantillas.plantillas_de(proyecto) or plantillas.detectar_stacks(proyecto)

    out = [f"# Project map — {proyecto}",
           f"# Generated by Dédalo on {time.strftime('%Y-%m-%d %H:%M')}.",
           "# Rule: when you change code, update/run its test BEFORE "
           "considering it done.",
           f"# Stacks: {', '.join(stacks) or '(none detected)'}",
           ""]

    out.append(f"## Modules ({len(modulos)})")
    out += _recortar([f"  {m}" for m in modulos] or ["  (none)"],
                     MAX_MODULOS, "ficheros")

    out += ["", f"## Tests ({len(tests)} files)"]
    lineas = []
    for t in tests:
        patron = _TESTS.get(EXT_CODIGO[os.path.splitext(t)[1].lower()])
        nombres = patron.findall(_leer(proyecto, t)) if patron else []
        lineas.append(f"  {t}: {len(nombres)} tests")
        lineas += [f"    - {n}" for n in nombres[:40]]
    out += _recortar(lineas or ["  (none)"], MAX_TESTS * 4, "líneas")

    rutas_http, comandos = [], []
    for f in codigo:
        if f in tests:
            continue
        texto = _leer(proyecto, f)
        if not texto:
            continue
        for _stack, patron in _RUTAS:
            for m in patron.finditer(texto):
                grupos = [g for g in m.groups() if g]
                ruta = grupos[-1]
                metodo = grupos[0].upper() if len(grupos) > 1 else ""
                rutas_http.append(f"  {metodo + ' ' if metodo else ''}{ruta}  ({f})")
        for _lib, patron in _CLI:
            for m in patron.finditer(texto):
                comandos.append(f"  {m.group(1)}  ({f})")

    out += ["", "## HTTP routes"]
    out += _recortar(sorted(set(rutas_http)), MAX_RUTAS, "rutas") or [
        "  (none detected: no Django/Flask/FastAPI/Express/actix/axum/Go "
        "router found)"]
    out += ["", "## CLI commands"]
    out += _recortar(sorted(set(comandos)), MAX_RUTAS, "comandos") or [
        "  (none detected)"]
    return "\n".join(out) + "\n"


def _mapear_sh_personalizado(proyecto):
    """Path of the project's mapear.sh if the user changed it, else None."""
    propio = rutas.mapear_sh(proyecto)
    base = os.path.join(plantillas.PLANTILLA_DIR, "mapear.sh")
    if not os.path.isfile(propio) or not os.path.isfile(base):
        return None
    return None if filecmp.cmp(propio, base, shallow=False) else propio


def generar(proyecto, destino=None, env=None):
    """Writes mapeo.txt and returns its path, or None if nothing was written.

    A customized `mapear.sh` (different from the bundled one) still wins: the
    user's script is what they want the agent to read.
    """
    destino = destino or rutas.mapeo(proyecto)
    texto = ""
    propio = _mapear_sh_personalizado(proyecto)
    if propio:
        antes = os.path.getmtime(destino) if os.path.exists(destino) else None
        try:
            r = subprocess.run(["bash", propio], cwd=proyecto, env=env,
                               capture_output=True, text=True, timeout=120)
            texto = r.stdout
        except (OSError, subprocess.TimeoutExpired):
            texto = ""
        # Older custom scripts write the file themselves instead of printing.
        if (not texto.strip() and os.path.exists(destino)
                and os.path.getmtime(destino) != antes):
            return destino
    if not texto.strip():
        texto = construir(proyecto)
    os.makedirs(os.path.dirname(destino) or ".", exist_ok=True)
    with open(destino, "w", encoding="utf-8") as f:
        f.write(texto)
    return destino
