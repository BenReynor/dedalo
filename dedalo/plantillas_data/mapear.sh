#!/usr/bin/env bash
# mapear.sh — Generates mapeo.txt: project map (modules -> tests).
# Used by dedalo.sh so the agent knows which tests exist and where to touch.
#
# Auto-detects the stack (Python/Django, Node, Rust) and lets the agent
# locate modules and tests. Overridable with BACKEND_DIR, FRONTEND_DIR,
# PY_BACKEND (see _env.sh).
#
# Usage:  bash mapear.sh > mapeo.txt
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# _env.sh shares the detection with gate.sh (it may live at the root or in gate_checks/)
if [ -f "$SCRIPT_DIR/gate_checks/_env.sh" ]; then
    source "$SCRIPT_DIR/gate_checks/_env.sh"
elif [ -f "$SCRIPT_DIR/_env.sh" ]; then
    source "$SCRIPT_DIR/_env.sh"
fi
if [ -z "${PROYECTO:-}" ]; then
    case "$SCRIPT_DIR" in
        */.dedalo/scripts) PROYECTO="$(dirname "$(dirname "$SCRIPT_DIR")")" ;;
        *) PROYECTO="$SCRIPT_DIR" ;;
    esac
fi

printf '# Project map — %s\n' "$PROYECTO"
printf '# Generated by mapear.sh on %s.\n' "$(date '+%F %H:%M')"
echo '# Rule: when you change code, update/run its test BEFORE considering it done.'
if [ -n "${PY_BACKEND:-}" ]; then
    echo "# Quick check: cd $BACKEND_DIR && $PY_BACKEND -m pytest <test> -q"
else
    echo "# Run the tests of the chosen module before finishing."
fi
echo ""

# ---- Backend: detect stack and list modules + tests ----
if [ -n "${BACKEND_DIR:-}" ] && [ -d "$BACKEND_DIR" ]; then
    # Python/Django: apps with models.py
    if [ -n "${PY_BACKEND:-}" ] && [ -f "$BACKEND_DIR/manage.py" ]; then
        echo "## Backend — apps and their tests"
        for dir in "$BACKEND_DIR"/*/; do
            [ -f "$dir/models.py" ] || continue
            app="$(basename "$dir")"
            [[ "$app" == "venv" || "$app" == "__pycache__" ]] && continue
            tests=""
            if [ -d "$dir/tests" ]; then
                # `find -printf` is GNU-only; glob + basename works on BSD.
                for tf in "$dir"/tests/test_*.py; do
                    [ -f "$tf" ] && tests="$tests$(basename "$tf") "
                done
            fi
            [ -f "$dir/tests.py" ] && tests="${tests}tests.py "
            if [ -n "${tests// /}" ]; then
                echo "  $app: ${tests% }"
            else
                echo "  $app: (no tests)"
            fi
        done
    elif [ -f "$BACKEND_DIR/package.json" ]; then
        # Node: modules in src/lib with their .test files.
        echo "## Backend (Node) — modules and tests"
        ( cd "$BACKEND_DIR" && find src lib -type f \( -name '*.ts' -o -name '*.js' \) 2>/dev/null \
            | grep -vE '\.(test|spec)\.' | sort ) || true
        echo "  (tests: *.test.ts|*.spec.ts next to each module)"
    elif [ -f "$BACKEND_DIR/Cargo.toml" ]; then
        echo "## Backend (Rust) — modules"
        ls "$BACKEND_DIR/src" 2>/dev/null || echo "  (no src/)"
        echo "  (tests: in src/**/tests/ or tests/)"
    fi

    echo ""
    echo "## Tests — functions per file"
    if [ -n "${PY_BACKEND:-}" ]; then
        while IFS= read -r tf; do
            rel="${tf#$PROYECTO/}"
            echo ""
            echo "  $rel:"
            grep -E '^[[:space:]]*def test_' "$tf" 2>/dev/null \
                | sed -E 's/^[[:space:]]*def (test_[a-zA-Z0-9_]+).*/\1/' \
                | while IFS= read -r t; do echo "    - $t"; done || true
        done < <(find "$BACKEND_DIR" -path '*/tests/test_*.py' -type f | head -200 | sort)
    fi
else
    echo "## Backend — (no BACKEND_DIR detected)"
fi

# ---- Frontend: source files ----
echo ""
echo "## Frontend — source files"
if [ -n "${FRONTEND_DIR:-}" ] && [ -d "$FRONTEND_DIR" ]; then
    if [ -n "${PY_FRONTEND:-}" ]; then
        ( cd "$FRONTEND_DIR" && find view services components data -name '*.py' 2>/dev/null | sort ) || true
    else
        ( cd "$FRONTEND_DIR" && find src components pages services -type f \( -name '*.ts' -o -name '*.js' -o -name '*.vue' \) 2>/dev/null | sort ) || true
    fi
else
    echo "  (no frontend directory)"
fi

# ---- URLs/routes of the stack ----
echo ""
echo "## Defined routes"
if [ -n "${BACKEND_DIR:-}" ] && [ -d "$BACKEND_DIR" ]; then
    if [ -f "$BACKEND_DIR/manage.py" ]; then
        ( cd "$BACKEND_DIR" && grep -rhnE "path\(['\"]" --include='urls.py' */urls.py 2>/dev/null \
            | sed -E "s/.*path\('([^']*)'.*/\1/" | sort -u | head -60 ) || true
    elif [ -f "$BACKEND_DIR/package.json" ]; then
        ( cd "$BACKEND_DIR" && grep -rnE "app\.(get|post|put|delete)\(" --include='*.ts' --include='*.js' src 2>/dev/null \
            | sed -E "s/.*(get|post|put|delete)\('([^']*)'.*/\2/" | sort -u | head -60 ) || true
    fi
else
    echo "  (no backend)"
fi
echo ""